/** Resolved inputs for a scaffold run. */
export interface InitOptions {
  /** Backend API URL the proxy forwards to while recording. */
  target: string;
  /** Port the proxy listens on (kept in sync with the Playwright client default). */
  port: number;
  /** Directory recordings are written to, relative to the config file. */
  dir: string;
  /** Overwrite existing files / script keys instead of leaving them untouched. */
  force: boolean;
  /**
   * Run the package manager: the Playwright CLI when Playwright is missing, and
   * an install when init added devDependencies (disable with --no-install).
   */
  install: boolean;
}

/** What happened to a single scaffolded file or package.json entry. */
export type ScaffoldStatus = 'created' | 'updated' | 'skipped';

export interface ScaffoldAction {
  /** Path relative to the project root. */
  relPath: string;
  status: ScaffoldStatus;
  /** Human-readable reason, shown for skips/updates. */
  detail?: string;
}

/** Outcome of {@link runInit}: one entry per file/edit it considered. */
export interface InitResult {
  actions: ScaffoldAction[];
  /** devDependencies written to package.json that are not installed yet. */
  addedDevDependencies: string[];
  /**
   * Whether the Playwright config tests a production build under E2E_BUILD:
   * `missing-in-scripts` when it does but a kept test:e2e script never sets it.
   */
  buildSwitch: 'on' | 'missing-in-scripts' | 'off';
  /** False when init couldn't tell the dev server's port and left APP_URL to set. */
  isAppUrlKnown: boolean;
}

/** How to build the app and serve the build, and where each server listens. */
export interface BuildServer {
  command: string;
  url: string;
  env: Record<string, string>;
  /** Where `dev` serves the app in the same framework. */
  devUrl: string;
}

