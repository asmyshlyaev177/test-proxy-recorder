/**
 * Parse `init` subcommand arguments. `argv` is the raw process argv with the
 * leading `node`, script, and `init` token already removed by the caller.
 */
export function parseInitArgs(argv: string[]): InitOptions {
  const program = new Command();

  program
    .name('test-proxy-recorder init')
    .description(
      'Scaffold test-proxy-recorder config + Playwright setup in the current directory',
    )
    .argument(
      '[target]',
      'Backend API URL your app uses in dev; the proxy forwards to it',
      DEFAULT_TARGET,
    )
    .option('-p, --port <number>', 'Proxy port', String(DEFAULT_PROXY_PORT))
    .option('-d, --dir <path>', 'Recordings directory', DEFAULT_DIR)
    .option(
      '-f, --force',
      'Overwrite existing files and package.json scripts',
      false,
    )
    .option(
      '--no-install',
      'Do not run the package manager (Playwright CLI, installing added devDependencies)',
    )
    .allowExcessArguments(false);

  // `argv` is already stripped to the init-specific tokens; tell commander to
  // treat it as user args (no node/script prefix to skip).
  program.parse(argv, { from: 'user' });

  const target = program.args[0] ?? DEFAULT_TARGET;
  const opts = program.opts<{
    port: string;
    dir: string;
    force: boolean;
    install: boolean;
  }>();

  const port = Number.parseInt(opts.port, 10);
  if (Number.isNaN(port) || port < 1025 || port > 65_535) {
    console.error('Error: Invalid port number. Must be between 1025 and 65535');
    process.exit(1);
  }

  return {
    target,
    port,
    dir: opts.dir,
    force: opts.force,
    install: opts.install,
  };
}

/** Past-tense label shown for each action in the summary. */
const STATUS_LABEL: Record<ScaffoldStatus, string> = {
  created: 'Created',
  updated: 'Updated',
  skipped: 'Skipped',
};

/**
 * Entry point for the `init` subcommand: optionally bootstrap Playwright, run the
 * scaffold, and print a per-file summary plus next steps. A thin, side-effecting
 * shell over the testable `parseInitArgs` / `runInit` pieces.
 */
export function initCommand(argv: string[], cwd: string = process.cwd()): void {
  const options = parseInitArgs(argv);

  maybeInstallPlaywright(options, cwd);

  const { actions, addedDevDependencies, buildSwitch, isAppUrlKnown } = runInit(
    options,
    cwd,
  );
  const isInstalled = installAddedDependencies(
    options,
    cwd,
    addedDevDependencies,
  );

  console.log('');
  for (const action of actions) {
    const label = STATUS_LABEL[action.status];
    const suffix = action.detail ? ` — ${action.detail}` : '';
    console.log(`${label.padEnd(7)} ${action.relPath}${suffix}`);
  }

  printNextSteps(
    actions,
    options,
    isInstalled ? [] : addedDevDependencies,
    detectPackageManager(cwd),
  );
  for (const line of getAppServerLines(buildSwitch, isAppUrlKnown)) {
    console.log(line);
  }
  printAgentPrompt(options);
}

/**
 * Render the copy-pasteable prompt for an AI coding agent to finish the
 * app-specific wiring `init` can't do. The text is the canonical, validated
 * prompt in `agent-prompt.md` (shipped beside this module — see the build's
 * onSuccess copy and the package `files` allowlist); we just fill in the
 * resolved proxy URL, backend target, and recordings dir.
 */
export function renderAgentPrompt(options: InitOptions): string {
  const template = readFileSync(
    new URL('agent-prompt.md', import.meta.url),
    'utf8',
  );
  return template
    .replaceAll('{{PROXY_URL}}', `http://localhost:${options.port}`)
    .replaceAll('{{TARGET}}', options.target)
    .replaceAll('{{DIR}}', options.dir)
    .trimEnd();
}

/** Print the AI-agent recommendation and the tailored prompt. */
function printAgentPrompt(options: InitOptions): void {
  console.log('');
  console.log(
    '🤖 Recommended: finish setup with an AI coding agent (Claude Code, Cursor, …).',
  );
  console.log(
    '   It wires the app-specific bits init can’t guess. Paste this prompt:',
  );
  console.log('');
  console.log('────────────────────────────────────────────────────────');
  console.log(renderAgentPrompt(options));
  console.log('────────────────────────────────────────────────────────');
}

/**
 * The one thing `init` can't do for you: route the app's backend calls through
 * the proxy, in dev/test only. Which env var the app reads, and how to scope it
 * to dev, is app-specific — so we print concrete, copy-pasteable guidance.
 */
function backendPointingLines(
  options: InitOptions,
  devWrapped: boolean,
): string[] {
  const proxyUrl = `http://localhost:${options.port}`;
  const lines = [
    "  1. Point your app's backend calls at the proxy — in dev/test only, never in production.",
    `     Set whatever env var your app reads its API base URL from to:  ${proxyUrl}`,
    `     (it talks to ${options.target} directly today; the proxy forwards there while`,
    '      recording and serves recordings on replay.)',
  ];
  const example = devWrapped
    ? `       "dev:app": "API_BASE_URL=${proxyUrl} <your dev command>"`
    : `       API_BASE_URL=${proxyUrl} <your dev/start command>`;
  lines.push(
    '     e.g. (use cross-env to make this work on Windows):',
    example,
  );
  return lines;
}

/**
 * Lines describing the Next.js SSR wiring outcome: a confirmation when we
 * injected `registerProxyFetch()` into the root layout, or the one line to add
 * by hand when we couldn't.
 */
function registerProxyFetchLines(actions: ScaffoldAction[]): string[] {
  const layout = actions.find((a) => isNextLayoutAction(a));
  if (!layout) return [];
  if (layout.status === 'updated') {
    return [
      `  • Next.js SSR fetch tagging wired into ${layout.relPath} via registerProxyFetch() (no-op in production).`,
      '     Record against a production build (next build && next start, on the same port so Playwright reuses it), not next dev.',
    ];
  }
  return [
    `  • Next.js: add SSR fetch tagging to your root layout (${layout.detail}):`,
    "       import { registerProxyFetch } from 'test-proxy-recorder/nextjs';",
    '       registerProxyFetch(); // top-level in app/layout.tsx — no-op in production',
    '       Using axios for SSR? call registerProxyAxios(yourInstance) instead. Record with build+start, not next dev.',
  ];
}

function getAppServerLines(
  buildSwitch: InitResult['buildSwitch'],
  isAppUrlKnown: boolean,
): string[] {
  const lines: string[] = [];
  if (!isAppUrlKnown) {
    lines.push(
      "  • Set APP_URL in playwright.config.ts to your dev server's URL and uncomment the app entry: init couldn't tell its port.",
    );
  }
  if (buildSwitch === 'on') {
    lines.push(
      '  • test:e2e and test:e2e:record test a production build (E2E_BUILD=1). A plain `playwright test` or `--ui` uses your dev server, to reproduce a failure by hand.',
    );
  }
  if (buildSwitch === 'missing-in-scripts') {
    lines.push(
      '  • playwright.config.ts tests a production build when E2E_BUILD is set, but your existing test:e2e scripts were kept; prefix them with E2E_BUILD=1 to use it.',
    );
  }
  return lines;
}

/** Print the "Next steps" block, tailored to what the scaffold actually did. */
function printNextSteps(
  actions: ScaffoldAction[],
  options: InitOptions,
  uninstalledDependencies: string[],
  pm: PackageManager,
): void {
  const pkgAction = actions.find((a) => a.relPath === 'package.json');
  const pwAction = actions.find((a) =>
    a.relPath.startsWith('playwright.config'),
  );
  const devWrapped = pkgAction?.detail?.includes('wrapped dev') ?? false;

  const step2 =
    pwAction?.status === 'skipped'
      ? `  2. Wire the proxy into your Playwright config (${pwAction.detail}):\n` +
        `       webServer: { command: 'test-proxy-recorder', url: 'http://localhost:${options.port}/__control', reuseExistingServer: true }`
      : '  2. Record: start `dev` (the proxy forwards to your dev backend), put your dev database in the state the tests expect (your own seed script), then run the test:e2e:record script (RECORD_MODE=1, one worker).';

  const step3 =
    pkgAction?.detail === 'no package.json found'
      ? '  3. Add scripts manually: "proxy": "test-proxy-recorder", "test:e2e": "playwright test".'
      : `  3. Commit ${options.dir}; test:e2e replays from it with the backend off.`;

  console.log('');
  console.log('Next steps:');
  if (uninstalledDependencies.length > 0) {
    console.log(
      `  0. Run \`${pm} install\`: init added ${uninstalledDependencies.join(', ')} to devDependencies, and \`${pm} run dev\` fails until it is installed.`,
    );
  }
  for (const line of backendPointingLines(options, devWrapped)) {
    console.log(line);
  }
  console.log(step2);
  console.log(step3);
  for (const line of registerProxyFetchLines(actions)) {
    console.log(line);
  }
  console.log(
    '  • Stuck in record/replay after an interrupted run? Run `test-proxy-recorder reset` (or `proxy:reset`) to return the proxy to transparent mode.',
  );
  console.log(
    '  • The test:e2e scripts set env vars as `NAME=1 command`, which Windows cmd and PowerShell reject (WSL and Git Bash are fine). There, prefix them with cross-env: `cross-env RECORD_MODE=1 playwright test --workers 1`.',
  );
  if (devWrapped) {
    console.log(
      `  • \`dev\` now runs the proxy and your app together through \`concurrently\`; your original command is \`${DEV_APP_SCRIPT}\`.`,
    );
    console.log(
      `     With no test recording or replaying, the proxy forwards everything to ${options.target} unchanged, so dev works as before.`,
    );
  }
}
