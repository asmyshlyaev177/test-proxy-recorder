/**
 * Render `test-proxy-recorder.config.ts`. The generated file mirrors the
 * documented config shape: a `defineConfig` default export with the resolved
 * target/port/dir filled in and the optional redaction block left commented out.
 */
export function renderConfig(options: InitOptions): string {
  return `import { defineConfig } from 'test-proxy-recorder';

// Generated by \`test-proxy-recorder init\`.
// Auto-discovered when you run \`test-proxy-recorder\` with no arguments.
// CLI flags always override the values set here.
export default defineConfig({
  // Backend the proxy forwards to: the one your app uses in dev. Point the app's
  // API base URL at the proxy instead; with no test recording or replaying, the
  // proxy passes every request through unchanged.
  target: '${options.target}',

  // Port the proxy listens on. Matches the Playwright client default
  // (override both with the TEST_PROXY_RECORDER_PORT env var).
  port: ${options.port},

  // Where recordings are written, relative to the directory the proxy runs in.
  // Commit this directory — CI replays from it.
  recordingsDir: '${options.dir}',

  // Secrets are redacted automatically (Authorization / Cookie / Set-Cookie).
  // Uncomment to redact extra headers or tokens embedded in bodies.
  // redaction: {
  //   headers: ['x-api-key'],
  //   bodyPatterns: [/sk_live_\\w+/g],
  //   allowCookies: ['theme'],
  // },
});
`;
}

/**
 * Render a fresh `playwright.config.ts` wired to the proxy's control endpoint.
 * `devCommand` starts the app the way `dev` does, or null when there is none.
 */
export function renderPlaywrightConfig(
  options: InitOptions,
  devCommand: string | null,
  devUrl: string | null,
  build: BuildServer | null,
): string {
  const app =
    devCommand && build
      ? renderBuildSwitch(devCommand, build)
      : renderDevServer(devCommand, devUrl);
  return `import { defineConfig } from '@playwright/test';

// Generated by \`test-proxy-recorder init\`.
${app.header}

export default defineConfig({
  testDir: './e2e',
  // Recording runs one test at a time, in order; replay runs them in parallel.
  fullyParallel: !process.env.RECORD_MODE,
  // Resets the proxy to transparent mode after the run.
  globalTeardown: './e2e/global-teardown.ts',
  use: { baseURL: APP_URL },
  // The proxy forwards to your dev backend, so tests use its data and a failure
  // can be reproduced by hand. A server that is already running is reused.
  webServer: [
    // Reads target/port/dir from test-proxy-recorder.config.ts. /__control
    // answers even when the backend is down.
    {
      command: 'test-proxy-recorder',
      url: 'http://localhost:${options.port}/__control',
      reuseExistingServer: true,
      timeout: 15_000,
    },
${app.entry}
  ],
});
`;
}

function renderDevServer(devCommand: string | null, devUrl: string | null) {
  if (devCommand && devUrl) {
    return {
      header: `// The URL your dev server serves the app on.\nconst APP_URL = '${devUrl}';`,
      entry: `${renderDevEntry(devCommand, '    ')},`,
    };
  }
  return {
    header: [
      '// Set APP_URL to the URL your dev server serves the app on, then uncomment',
      '// the app entry in webServer.',
      `const APP_URL = '${PLACEHOLDER_DEV_URL}';`,
    ].join('\n'),
    entry: `${renderDevEntry(devCommand ?? '<your dev command>', '    // ')},`,
  };
}

/** The dev server entry, reused when it already runs. */
function renderDevEntry(devCommand: string, indent: string): string {
  return [
    '{',
    `  command: '${devCommand}',`,
    '  url: APP_URL,',
    '  reuseExistingServer: true,',
    '  // pnpm -r/--parallel runs each package in its own process group, which the',
    '  // default SIGKILL leaves running on its port; on SIGTERM pnpm stops them.',
    "  gracefulShutdown: { signal: 'SIGTERM', timeout: 5_000 },",
    '}',
  ]
    .map((line) => `${indent}${line}`)
    .join('\n');
}

function renderBuildSwitch(devCommand: string, build: BuildServer) {
  const env = Object.entries(build.env)
    .map(([key, value]) => `${key}: '${value}'`)
    .join(', ');
  return {
    header: [
      '// The test:e2e scripts set E2E_BUILD=1 to test a production build, rebuilt',
      '// every run. A plain `playwright test` (or --ui) uses your dev server.',
      'const IS_BUILD = Boolean(process.env.E2E_BUILD);',
      '// The URLs your build and dev servers serve the app on.',
      `const APP_URL = IS_BUILD ? '${build.url}' : '${build.devUrl}';`,
    ].join('\n'),
    entry: [
      '    IS_BUILD',
      `      ? { command: '${build.command}', url: APP_URL, env: { ${env} } }`,
      `      : ${renderDevEntry(devCommand, '        ').trimStart()},`,
    ].join('\n'),
  };
}

/** Render the per-test proxy fixture (`e2e/fixtures.ts`). */
export function renderFixtures(): string {
  return String.raw`import { test as base, type Page } from '@playwright/test';
import { playwrightProxy } from 'test-proxy-recorder';

// External domains the browser calls directly (auth, CDN, analytics, ...),
// e.g. /cognito-.*\.amazonaws\.com/. Calls that go through the proxy, including
// via a dev-server proxy such as Vite's server.proxy, are recorded without it.
// Leave it undefined until you need it: replay loads a HAR for any pattern.
const CLIENT_SIDE_URL: RegExp | undefined = undefined;

// The test:e2e:record script sets RECORD_MODE=1 to hit the real API and rewrite the
// recordings (one worker); without it, tests replay from the committed files.
const MODE = process.env.RECORD_MODE ? 'record' : 'replay';

export const test = base.extend<{ page: Page }>({
  page: async ({ context }, use, testInfo) => {
    const page = await context.newPage();
    await playwrightProxy.before(page, testInfo, MODE, { url: CLIENT_SIDE_URL });
    await use(page);
  },
});

export { expect } from '@playwright/test';
`;
}

/** Render the global teardown (`e2e/global-teardown.ts`). */
export function renderTeardown(): string {
  return `import { playwrightProxy } from 'test-proxy-recorder';

// Runs once after the whole suite — resets the proxy to transparent mode and
// redacts secrets from the recorded .har files (HAR redaction happens here, not
// per-test). Do NOT call teardown() per-test (afterAll): it flips the global
// mode and breaks parallel replay.
export default async function globalTeardown() {
  await playwrightProxy.teardown().catch((err: unknown) => {
    console.warn('test-proxy-recorder teardown', err);
  });
}
`;
}

/** Next.js project info detected from `package.json`, or null when not Next.js. */
export interface NextjsInfo {
  /** Major version parsed from the declared range, or null when not numeric. */
  major: number | null;
}

/** Pull the leading major version out of a semver range (`^16.2.4` → 16). */
function parseMajor(range: string): number | null {
  const match = range.match(/(\d+)/);
  return match ? Number.parseInt(match[1], 10) : null;
}

/**
 * Detect a Next.js project from its declared `next` dependency. Returns the
 * major version (when numeric), or null when the project does not depend on
 * Next.js. Used only to decide whether to wire SSR fetch tagging.
 */
export function detectNextjs(cwd: string): NextjsInfo | null {
  const pkgPath = path.join(cwd, 'package.json');
  if (!existsSync(pkgPath)) return null;
  try {
    const pkg = JSON.parse(readFileSync(pkgPath, 'utf8')) as PackageJson;
    const range = pkg.dependencies?.next ?? pkg.devDependencies?.next;
    if (!range) return null;
    return { major: parseMajor(range) };
  } catch {
    return null;
  }
}

